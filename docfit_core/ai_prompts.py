def all_prompts() -> list[tuple[str, str, str, bool]]:
    """(이름, 설명, 요청문, 라벨형식 여부)"""
    return [(n, d, b, True) for n, d, b in PROMPTS] + [(n, d, b, False) for n, d, b in PLAIN_PROMPTS]


def build_prompt(name: str, content: str) -> str:
    for title, _, body, labeled in all_prompts():
        if title == name:
            memo = content.strip() or "[여기에 메모를 붙여넣으세요]"
            parts = [body, "", "[메모]", memo]
            if labeled:
                parts += ["", LABEL_RULES, "", LABEL_EXAMPLE]
            return "\n".join(parts)
    raise KeyError(name)
